/** تصحيحات إملائية في نصوص العقد */
const LABEL_FIXES = {
  u1_rule2: { label: "الالتزام بالعناوين الرسمية الستة لآثار العقيدة دون تغيير" },
};

const PAIRS = [
  ["unit01_aqidah_mindmap.json", "unit01_aqidah_standard.json"],
  ["unit02_quran_means_mindmap.json", "unit02_quran_means_standard.json"],
  ["unit03_islam_messages_mindmap.json", "unit03_islam_messages_standard.json"],
  ["unit04_intellect_mindmap.json", "unit04_intellect_standard.json"],
];

let autoFilled = 0;
let curatedFilled = 0;
const problems = [];

for (const [mmFile, stdFile] of PAIRS) {
  const mm = read(mmFile);
  const std = read(stdFile);
  const titled = collectTitled(std.detailed_explanation);

  const visit = (node) => {
    for (const child of node.children ?? []) visit(child);
    const fix = LABEL_FIXES[node.id];
    if (fix) node.label = fix.label;
    if (node.details) return;

    // 0) العقدة الجذرية: تُشرح بالكفاءة المستهدفة للوحدة
    if (node.id.endsWith("_root") && std.learning_objective) {
      node.details = std.learning_objective;
      autoFilled += 1;
      return;
    }

    // 1) شرح مُدقق يدويًا
    if (CURATED[node.id]) {
      node.details = CURATED[node.id].details;
      if (CURATED[node.id].proof) node.proof = CURATED[node.id].proof;
      curatedFilled += 1;
      return;
    }

    // 2) استخراج تلقائي من detailed_explanation
    const label = norm(node.label);
    let best = null;
    let bestScore = 0;
    for (const c of titled) {
      const t = norm(c.title);
      const score = t === label ? 1 : t.includes(label) || label.includes(t) ? 0.9 : 0;
      if (score > bestScore) {
        bestScore = score;
        best = c;
      }
    }
    if (best && bestScore >= 0.9) {
      node.details = best.text;
      if (best.proof) node.proof = best.proof;
      autoFilled += 1;
      return;
    }

    problems.push(`${mmFile} :: ${node.id} :: ${node.label}`);
  };

  visit(mm.root);
  write(mmFile, mm);
  console.log(`${mmFile}: تمت المعالجة`);
}

const stillMissing = [];
for (const [mmFile] of PAIRS) {
  const mm = read(mmFile);
  const walk = (n) => {
    if (!(n.children || []).length && !n.details) stillMissing.push(`${mmFile} :: ${n.id}`);
    (n.children || []).forEach(walk);
  };
  walk(mm.root);
}

console.log(`\nتلقائي: ${autoFilled} · مُدقق يدويًا: ${curatedFilled}`);
if (problems.length)
  console.log(`لم يُعثر على شرح: ${problems.length}\n  ${problems.join("\n  ")}`);
if (stillMissing.length) {
  console.error(
    `\n❌ ما زالت ${stillMissing.length} عقدة بلا شرح:\n  ${stillMissing.join("\n  ")}`
  );
  process.exit(1);
}
console.log("✅ كل عقد الخرائط الذهنية لها شرح الآن.");
