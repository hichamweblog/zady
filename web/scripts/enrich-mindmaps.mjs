/**
 * يثري عقد الخرائط الذهنية (الأوراق) بحقل details/proof.
 *
 * المشكلة: 39 عقدة من 72 كانت بلا شرح، فكان الطالب ينقر عنصراً في الفهرس
 * فلا يجد شيئاً. هذا السكربت:
 *   1) يستخرج تلقائياً الشروح الجاهزة من detailed_explanation (title + explanation)
 *   2) يطبّق خريطة شروح مُدققة للعقد التي لا يوجد لها نظير مباشر في البيانات
 *   3) يفشل صراحةً إذا بقيت عقدة بلا شرح
 *
 * التشغيل: node scripts/enrich-mindmaps.mjs
 */
import fs from "node:fs";
import path from "node:path";

const DIR = path.join(import.meta.dirname, "..", "src", "data", "lessons");
const read = (f) => JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
const write = (f, d) =>
  fs.writeFileSync(path.join(DIR, f), `${JSON.stringify(d, null, 2)}\n`, "utf8");

const norm = (s) =>
  (s || "")
    .replace(/[\u064B-\u0652\u0640]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/[^\p{L}\p{N} ]/gu, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

/** يجمع كل الأزواج (title, explanation) من شجرة detailed_explanation */
function collectTitled(node, out = []) {
  if (!node || typeof node !== "object") return out;
  if (Array.isArray(node)) {
    node.forEach((n) => collectTitled(n, out));
    return out;
  }
  if (node.title && (node.explanation || node.definition)) {
    out.push({
      title: node.title,
      text: node.explanation || node.definition,
      proof: node.quranic_proof_warsh || node.quranic_proof || null,
    });
  }
  Object.values(node).forEach((v) => collectTitled(v, out));
  return out;
}

