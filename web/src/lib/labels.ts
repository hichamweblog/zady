/**
 * تسميات قصيرة للتصنيفات الطويلة.
 *
 * تصنيفات بنك الأسئلة أسماء وصفية طويلة («مدرب النصوص الشرعية وبنك تطبيقات
 * الاستخراج (20 - 30)»)، فكانت شريحة التصفية تشغل ثلاثة أسطر على الهاتف وتدفع
 * المحتوى خارج الشاشة. هنا يُختصر التصنيف إلى كلمة أو كلمتين مع الحفاظ على
 * الاسم الكامل في `title` (وعلى الشاشات الكبيرة).
 */
const EXPLICIT: Record<string, string> = {
  "الأسئلة المباشرة والنظرية المفاهيمية": "أسئلة مباشرة",
  "أسئلة الفهم والاستنتاج والربط بين الدروس": "فهم واستنتاج",
  "أسئلة البكالوريا السابقة الرسمية (2020 - 2024)": "بكالوريا سابقة",
  "مدرب النصوص الشرعية وبنك تطبيقات الاستخراج (20 - 30)": "استخراج من النصوص",
  "آثار العقيدة على الفرد": "أثر على الفرد",
  "آثار العقيدة على المجتمع": "أثر على المجتمع",
  "الأسس والمفاهيم": "أسس ومفاهيم",
};

/** أفعال/كلمات مفتاحية تُختصر تلقائيًا حين لا يوجد تعيين صريح */
const KEYWORDS: [RegExp, string][] = [
  [/استخراج|النصوص الشرعية/, "استخراج من النصوص"],
  [/بكالوريا سابقة|السابقة الرسمية/, "بكالوريا سابقة"],
  [/الفهم والاستنتاج/, "فهم واستنتاج"],
  [/مباشرة|نظرية/, "أسئلة مباشرة"],
  [/على الفرد/, "أثر على الفرد"],
  [/على المجتمع/, "أثر على المجتمع"],
  [/الفروق|المقارنة/, "فروق ومقارنة"],
  [/التعليل|علل/, "تعليل"],
];

/** حد أقصى لطول التسمية القصيرة (حروف) */
const MAX = 22;

export function shortCategory(category: string): string {
  const direct = EXPLICIT[category];
  if (direct) return direct;

  for (const [pattern, label] of KEYWORDS) {
    if (pattern.test(category)) return label;
  }

  // احتياط: أول ثلاث كلمات دون تجاوز الحد
  const words = category
    .replace(/\([^)]*\)/g, "")
    .trim()
    .split(/\s+/);
  let out = "";
  for (const word of words) {
    if ((out + " " + word).trim().length > MAX) break;
    out = (out ? out + " " : "") + word;
  }
  return out || category.slice(0, MAX);
}
